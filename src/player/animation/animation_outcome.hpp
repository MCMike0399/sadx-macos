enum class Failure {
    None,
    UnavailableField,
    NullResource,
    UnresolvedResource,
    MissingArena,
    WorkFailed,
    MissingBlendOwner,
    BlendFailed,
    LoopNoProgress,
    ObjectCapacity,
    UnavailablePose,
    UnavailableKey
};
struct Outcome {
    Failure failure = Failure::None;
    Phase phase = Phase::None, nested_phase = Phase::None;
    bool nested_transition = false;
    std::optional<TaskWorkFailure> work_failure;
    std::string unavailable_resource_reason;
    bool completed = false;
    std::uint32_t wrap_iterations = 0;
    explicit operator bool() const noexcept { return failure == Failure::None && completed; }
};
struct Stop {
    Outcome result;
};
