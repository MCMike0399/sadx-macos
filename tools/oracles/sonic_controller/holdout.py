"""Fresh deterministic Sonic holdout against old/native and unchanged original engines.

This never imports or executes preserved reset/animation reserved cohorts. Every
source field, inherited source discrepancy, native ABI word and input identity is
retained. Inputs are generated by this committed definition; nothing is excluded.
"""
import argparse
import ctypes
import gzip
import hashlib
import importlib
import json
from pathlib import Path
import random
import struct
import sys

from observe import invoke, sha

ROOT = Path(__file__).resolve().parents[3]
sys.path[:0] = [str(ROOT / "tools/lib"), str(ROOT / "tools/oracles")]


def fixtures(module, slug):
    rows = list(module.fixtures())
    rng = random.Random(354291)
    floats = [0, 0x80000000, 1, 0x80000001, 0x7fc12345, 0x7f812345,
              0x3f800000, 0xbf800000]
    for precision in (0, 0x200, 0x300):
        for rounding in (0, 0x400, 0x800, 0xc00):
            for _ in range(128):
                row = rng.choice(rows).copy()
                row[1] = precision | rounding | 0x7f
                if slug == "sonic_player":
                    row[8] = rng.randrange(65536)
                    row[28] = rng.randrange(65536)
                    row[29] = rng.randrange(65536)
                    row[31] = rng.randrange(256)
                    row[32] = rng.getrandbits(32)
                    for field in (11, 12, 13):
                        row[field] = rng.choice(floats + [struct.unpack("<I", struct.pack("<f", rng.uniform(-0.025, 0.025)))[0]])
                else:
                    row[10] = rng.randrange(65536)
                    row[13] = rng.randrange(65536)
                    row[15] = rng.randrange(65536)
                    row[16] = rng.randrange(65536)
                    row[18] = rng.randrange(65536)
                    row[20] = rng.choice(floats)
                    row[26] = rng.choice(floats)
                    row[29] = rng.choice((0, 2, 4, 0x20, 0x402))
                    row[30] = rng.choice((0, 2, 4, 0x20, 0x402))
                yield row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exe", type=Path)
    parser.add_argument("old", type=Path, help="Frozen baseline directory")
    parser.add_argument("current", type=Path, help="Current reference library directory")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    from pe_image import PEImage
    from extract import SOURCE_SHA256
    import unicorn
    image = PEImage(args.exe)
    if image.sha256 != SOURCE_SHA256 or unicorn.__version__ != "2.1.4":
        raise ValueError("Original engine identity differs")
    summary = {}
    for slug in ("sonic_player", "sonic_actions"):
        module = importlib.import_module("verify_original_" + slug)
        source = module.SonicOriginal(image) if slug == "sonic_player" else module.ActionsOriginal(image)
        old_path = args.old / ("player/sonic_player.dylib" if slug == "sonic_player" else "sonic_actions.dylib")
        new_path = args.current / (slug + ".dylib")
        old, new = ctypes.CDLL(str(old_path.resolve())), ctypes.CDLL(str(new_path.resolve()))
        constants = list(b"".join(image.read(address, 4) for address in module.CONSTANTS))
        stream = bytearray()
        differences = []
        source_differences = []
        input_digest = hashlib.sha256()
        function = "sadx_native_sonic_player" if slug == "sonic_player" else "sadx_native_sonic_action"
        count = 0
        for case, row in enumerate(fixtures(module, slug)):
            input_digest.update(struct.pack("<" + str(len(row)) + "I", *row))
            expected = source.run(row)
            arguments = [constants, len(constants), row, [0] * 40] if slug == "sonic_player" else [constants, len(constants), row, 52, [0] * 32, 32]
            old_return, old_words = invoke(old, function, arguments)
            new_return, new_words = invoke(new, function, arguments)
            if (old_return, old_words) != (new_return, new_words):
                differences.append(case)
            inherited = [[int(field), value, old_words[int(field)]] for field, value in expected[0].items()
                         if value != old_words[int(field)]]
            if inherited:
                source_differences.append(dict(case=case, differences=inherited))
            record = dict(case=case, input=row, source=expected, old_return=old_return,
                          old_words=old_words, new_return=new_return, new_words=new_words)
            stream.extend((json.dumps(record, separators=(",", ":")) + "\n").encode())
            count += 1
        (args.output / (slug + ".jsonl.gz")).write_bytes(gzip.compress(bytes(stream), mtime=0))
        summary[slug] = dict(records=count, input_sha256=input_digest.hexdigest(),
                             complete_observation_sha256=sha(stream),
                             old_library_sha256=sha(old_path.read_bytes()),
                             new_library_sha256=sha(new_path.read_bytes()),
                             native_differences=differences,
                             inherited_source_differences=source_differences,
                             exact_old_new=not differences)
        print(slug, count, len(differences), "old/new differences", flush=True)
    summary["source_sha256"] = image.sha256
    summary["definition_sha256"] = sha(Path(__file__).read_bytes())
    summary["limits"] = ["Controlled source fixtures, not a Session/gameplay journey or Windows capture",
                         "Every original discrepancy is retained individually; none is excluded",
                         "Fresh definition requires Root's independent adequacy review"]
    (args.output / "report.json").write_text(json.dumps(summary, indent=2) + "\n")
    return int(any(not value["exact_old_new"] for key, value in summary.items() if key in ("sonic_player", "sonic_actions")))


if __name__ == "__main__":
    raise SystemExit(main())
