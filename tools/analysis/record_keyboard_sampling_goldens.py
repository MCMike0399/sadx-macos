"""Record actual DLL math for an explicitly specified keyboard sampling sequence.

Raw ramps here are literal source-derived expectations, not native execution.
"""
import argparse,hashlib,json,pathlib
import sys,pathlib as _pl;sys.path[:0]=[str(_pl.Path(__file__).resolve().parents[2]/'tools'/d) for d in('lib','oracles')]  # run from anywhere
from pe_image import PEImage
from verify_original_input_mod_axes import Original,INPUT_SHA
# Physical events and expected current raw x/y after one tick:8192 source ramp.
# Scancode0 means no event; focus=true is native focus-clearing policy/source ease.
STEPS=[(79,True,False,False,8192,0),(79,True,True,False,16384,0),
       (81,True,False,False,24576,8192),(80,True,False,False,16384,16384),
       (82,True,False,False,8192,8192),(79,False,False,False,0,0),
       (80,False,False,False,0,0),(82,False,False,False,0,8192),
       (40,True,False,False,0,16384),(40,True,True,False,0,24576),
       (0,False,False,True,0,16384),(0,False,False,False,0,8192),
       (0,False,False,False,0,0)]
def main():
    p=argparse.ArgumentParser();p.add_argument('input_mod',type=pathlib.Path);p.add_argument('--output',type=pathlib.Path,required=True);a=p.parse_args()
    image=PEImage(a.input_mod)
    if image.sha256!=INPUT_SHA:raise RuntimeError('DLL identity mismatch')
    oracle=Original(image);records=[]
    for rc in range(4):
        control=0x1f80|(rc<<13)
        for scancode,down,repeat,focus,x,y in STEPS:
            output,status=oracle.run([x,y,0,0],1,control)
            records.append({'mxcsr':control,'event':[scancode,down,repeat,focus],
                            'raw_left':[x,y],'output':output,'emulator_mxcsr':status})
    record={'dll_sha256':image.sha256,'scope':'actual DLL scalar instructions; source-derived literal ramp sequence; no Windows event dispatch','records':records}
    a.output.write_text(json.dumps(record,indent=2)+'\n')
    header=pathlib.Path('tests/fixtures/input_keyboard_goldens.hpp')
    lines=['#pragma once','#include <cstdint>','// Generated by record_keyboard_sampling_goldens.py from pinned actual DLL instructions.',
           '// Exact DLL/fixture provenance: reference/keyboard-sampling-goldens.json.',
           'struct KeyboardGolden { std::uint32_t mxcsr; int scancode; bool down, repeat, focus; int raw_x, raw_y; std::uint32_t x, y, magnitude; };',
           'inline constexpr KeyboardGolden keyboard_goldens[] = {']
    for r in records:
        e=r['event'];out=r['output'];raw=r['raw_left'];bools=lambda b:'true' if b else 'false'
        lines.append(f'    {{0x{r["mxcsr"]:x}, {e[0]}, {bools(e[1])}, {bools(e[2])}, {bools(e[3])}, {raw[0]}, {raw[1]}, 0x{out[0]:08x}, 0x{out[1]:08x}, 0x{out[2]:08x}}},')
    lines+=['};',''];header.write_text('\n'.join(lines))
    print('Recorded',len(records),'actual instruction goldens; header SHA',hashlib.sha256(header.read_bytes()).hexdigest())
if __name__=='__main__':main()
