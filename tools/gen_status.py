#!/usr/bin/env python3
"""Regenerate docs/STATUS.md from recorded facts: the newest gate record, the oracle
comparison index, the survey report and the source tree. Facts only; the prose about
what the numbers mean lives in docs/ROADMAP.md and docs/REVIEW-*.md."""
import glob,json,os,pathlib,re,subprocess,sys,datetime
ROOT=pathlib.Path(__file__).resolve().parents[1]
def newest(pattern):
    files=sorted(glob.glob(str(ROOT/pattern)),key=os.path.getmtime)
    return pathlib.Path(files[-1]) if files else None
def main():
    gate=newest('reference/production-integration-*/*-gate.json')
    g=json.loads(gate.read_text()) if gate else {}
    comparisons=sorted(glob.glob(str(ROOT/'reference/production-integration-*/post-repair-comparisons/original-*.json')))
    passing=0;failing=[]
    for c in comparisons:
        try:d=json.loads(open(c).read())
        except Exception:continue
        ok=None
        if 'passed' in d:ok=bool(d['passed'])
        elif 'mismatch_count' in d:ok=d['mismatch_count']==0
        elif 'mismatched_words' in d:ok=d['mismatched_words']==0
        elif 'mismatches' in d:n=d['mismatches'];ok=(len(n) if isinstance(n,list) else n)==0
        if ok:passing+=1
        else:failing.append(os.path.basename(c)+('' if ok is False else ' (unknown key)'))
    survey=newest('reference/production-integration-*/sadx-boot-survey.txt')
    survey_text=survey.read_text() if survey else ''
    stops=re.findall(r'^  (\S+)\s+site (\S+)\s+calls (\d+)',survey_text,re.M)
    frames=re.search(r'frames completed: (\d+)',survey_text)
    src=sorted(p for p in ROOT.glob('src/**/*') if p.suffix in('.cpp','.hpp','.mm'))
    areas={}
    for p in src:
        area=p.relative_to(ROOT/'src').parts[0];areas[area]=areas.get(area,0)+sum(1 for _ in p.open('rb'))
    units=len(list((ROOT/'tests/unit').glob('*.cpp')))+len(list((ROOT/'tests/unit').glob('*.mm')))
    probes=len(list((ROOT/'tests/probes').glob('native_*_probe.cpp')))
    oracles=sum(1 for l in (ROOT/'tools/oracles/manifest.tsv').read_text().splitlines() if l.strip() and not l.startswith('#'))
    head=subprocess.run(['git','rev-parse','--short','HEAD'],cwd=ROOT,capture_output=True,text=True).stdout.strip() or 'uncommitted'
    out=[]
    out.append('# Status (generated by tools/gen_status.py — do not edit by hand)\n')
    out.append(f'Generated {datetime.datetime.now().astimezone().isoformat(timespec="minutes")} at commit `{head}`.\n')
    out.append('## Milestone\n')
    out.append('Current milestone: **M1 — the whole game runs headless (hybrid runtime)**. See `docs/ROADMAP.md`. M0 is complete.\n')
    out.append('## Last recorded gate\n')
    if gate:
        out.append(f'`{gate.relative_to(ROOT)}`: exit {g.get("exit_status")}, passed={g.get("passed")}, {g.get("native_programs")} native programs, {g.get("python_tests")} Python tests.\n')
        for lim in g.get('limits',[]):out.append(f'* {lim}')
        out.append('')
    else:out.append('No gate recorded yet.\n')
    out.append('## Verification inventory\n')
    out.append(f'* Unit test programs: {units}\n* Native probes: {probes}\n* Oracle targets: {oracles}; comparison reports passing: {passing}/{len(comparisons)}'+(f' (failing: {", ".join(failing)})' if failing else '')+'\n')
    out.append('## Native execution (sadx-boot survey)\n')
    if survey:
        out.append(f'`{survey.relative_to(ROOT)}`: frames completed {frames.group(1) if frames else "?"} (survey policy). Unported owners reached, first-reached order:\n')
        out.append('| Path | Site | Calls |\n|---|---|---|')
        for path,site,calls in stops:out.append(f'| `{path}` | {site} | {calls} |')
        out.append('')
        assumptions=[l[len("assumption: "):] for l in survey_text.splitlines() if l.startswith('assumption: ')]
        out.append(f'Assumptions reported by the runtime: {len(assumptions)} (full text in the survey file).\n')
    out.append('## Source tree\n')
    out.append('| Area | Lines |\n|---|---|')
    for a,n in sorted(areas.items(),key=lambda kv:-kv[1]):out.append(f'| `src/{a}` | {n} |')
    out.append(f'| total | {sum(areas.values())} |\n')
    out.append('## Hybrid runtime progress (M1+)\n')
    inv=ROOT/'reference/inventory/functions.json'
    if inv.exists():
        d=json.loads(inv.read_text());out.append(f'* Functions inventoried: {len(d)}')
    else:out.append('* Function inventory: not built yet (`docs/METHOD.md` §2).')
    overrides=ROOT/'src/guest/overrides.tsv'
    if overrides.exists():
        n=sum(1 for l in overrides.read_text().splitlines() if l.strip() and not l.startswith('#'));out.append(f'* Native overrides bound: {n}')
    else:out.append('* Guest/override table: not built yet (M1).')
    out.append('')
    (ROOT/'docs/STATUS.md').write_text('\n'.join(out)+'\n')
    print('docs/STATUS.md written')
    return 0
if __name__=='__main__':sys.exit(main())
