#!/usr/bin/env python3
"""Regenerate docs/STATUS.md from recorded facts: the newest gate record, the tracked oracle
reports (reference/oracle-reports/<slug>.json, read through tools/oracles/verdict.py), the
survey report and the source tree. Facts only; the prose about what the numbers mean lives in
docs/ROADMAP.md and docs/REVIEW-*.md."""
import glob,json,os,pathlib,re,subprocess,sys,datetime
ROOT=pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/oracles'))
from verdict import verdict
from check_readability import snapshot as readability_snapshot, totals as readability_totals
LAYERS=['cpu','loader','math','engine','input','player','game','runtime','guest','hle','platform','apps']
def newest(pattern):
    files=sorted(glob.glob(str(ROOT/pattern)),key=os.path.getmtime)
    return pathlib.Path(files[-1]) if files else None
def oracle_table():
    """slug -> (verdict, reason, probe exists)"""
    rows={}
    for s in sorted((ROOT/'tools/oracles').glob('verify_original_*.py')):
        slug=s.name[len('verify_original_'):-3];rep=ROOT/f'reference/oracle-reports/{slug}.json'
        if rep.exists():
            try:v,why=verdict(json.loads(rep.read_text()))
            except Exception as e:v,why='fail',f'unreadable: {e}'
        else:v,why='missing','no tracked report'
        rows[slug]=(v,why,(ROOT/f'tests/probes/native_{slug}_probe.cpp').exists())
    return rows

def distinct_journeys(rows):
    """Smoke and route checks can both report R1; retain any conflicting failure."""
    journeys = {}
    for row in rows:
        key = (row['row'], row['name'])
        if key not in journeys or row['verdict'] != 'pass':
            journeys[key] = row
    return list(journeys.values())

def native_evidence(gate):
    rows = gate.get('native_journeys', [])
    passed = [row['journey'] for row in rows if row.get('exit_status') == 0
              and row.get('result', {}).get('passed') is True]
    if not passed:
        return 'No native checkpoints certified by the last recorded gate.'
    return ('Native checkpoints certified by the last recorded gate: **' +
            ', '.join(dict.fromkeys(passed)) + '**.')
def main():
    gate=newest('reference/production-integration-*/*-gate.json')
    g=json.loads(gate.read_text()) if gate else {}
    oracles=oracle_table()
    buckets={}
    for slug,(v,why,_) in oracles.items():buckets.setdefault(v,[]).append((slug,why))
    survey=newest('reference/production-integration-*/sadx-boot-survey.txt')
    survey_text=survey.read_text() if survey else ''
    stops=re.findall(r'^  (\S+)\s+site (\S+)\s+calls (\d+)',survey_text,re.M)
    frames=re.search(r'frames completed: (\d+)',survey_text)
    src=sorted(p for p in ROOT.glob('src/**/*') if p.suffix in('.cpp','.hpp','.mm'))
    layers={}
    for p in src:
        layer=p.relative_to(ROOT/'src').parts[0];layers.setdefault(layer,[0,0]);layers[layer][0]+=1;layers[layer][1]+=len(p.read_bytes().splitlines())
    units=len(list((ROOT/'tests/unit').glob('*.cpp')))+len(list((ROOT/'tests/unit').glob('*.mm')))
    probes=len(list((ROOT/'tests/probes').glob('native_*_probe.cpp')))
    head=subprocess.run(['git','rev-parse','--short','HEAD'],cwd=ROOT,capture_output=True,text=True).stdout.strip() or 'uncommitted'
    out=[]
    out.append('# Status (generated by tools/gate/gen_status.py — do not edit by hand)\n')
    out.append(f'Generated {datetime.datetime.now().astimezone().isoformat(timespec="minutes")} at commit `{head}`.\n')
    out.append('## Route evidence\n')
    out.append(native_evidence(g) + '\n')
    out.append('The current route and next checkpoint are defined in `docs/GOAL.md`; '
               'milestone definitions remain in `docs/ROADMAP.md`. Journey results alone '
               'do not certify a whole roadmap milestone.\n')
    out.append('## Last recorded gate\n')
    if gate:
        out.append(f'`{gate.relative_to(ROOT)}`: exit {g.get("exit_status")}, passed={g.get("passed")}, {g.get("native_programs")} native programs, {g.get("python_tests")} Python tests.\n')
        for lim in g.get('limits',[]):out.append(f'* {lim}')
        out.append('')
    else:out.append('No gate recorded yet.\n')
    if g.get('journeys'):
        out.append('## Visible journeys (last gate)\n')
        out.append('| Row | Journey | Result |\n|---|---|---|')
        for journey in distinct_journeys(g['journeys']):
            out.append(f'| {journey["row"]} | {journey["name"]} | {journey["verdict"]} |')
        out.append('')
        out.append('R5–R6 remain unverified by this gate. See `docs/GOAL.md`.\n')
    if g.get('native_journeys'):
        out.append('## Native checkpoints (last gate)\n')
        out.append('| Checkpoint | Result | Frames |\n|---|---|---|')
        for checkpoint in g['native_journeys']:
            result = checkpoint.get('result', {})
            passed = checkpoint.get('exit_status') == 0 and result.get('passed') is True
            out.append(f'| {checkpoint["journey"]} | {"pass" if passed else "FAIL"} | {result.get("frames", "unreported")} |')
        out.append('')
        out.append('These are connected native menu/save checkpoints. N3 remains partial until CharacterSelect works; native story/gameplay N4–N5 and gameplay63FPS remain unverified. See `docs/GOAL.md`.\n')
    else:
        out.append('Native N1–N5 were not recorded by this gate. See `docs/GOAL.md`.\n')
    out.append('## Verification inventory\n')
    out.append(f'* Unit test programs: {units}\n* Native probes: {probes}\n* Oracles: {len(oracles)} — '
               +', '.join(f'{len(buckets.get(k,[]))} {k}' for k in('pass','partial','fail','missing'))
               +' (rules: `tools/oracles/verdict.py`; "partial" = every compared value matches but FP status/exception flags differ, see the report\'s `limits`).\n')
    for k in('fail','partial','missing'):
        if buckets.get(k):
            out.append(f'{k.capitalize()}:\n')
            for slug,why in buckets[k]:out.append(f'* `{slug}`: {why}')
            out.append('')
    out.append('## Historical reference boot survey\n')
    if survey:
        out.append('This development survey is historical evidence, not the current native app frontier. '
                   'Use the recorded native checkpoints above and `docs/GOAL.md` for that frontier.\n')
        out.append(f'`{survey.relative_to(ROOT)}`: frames completed {frames.group(1) if frames else "?"} (survey policy). Unported owners reached, first-reached order:\n')
        out.append('| Path | Site | Calls |\n|---|---|---|')
        for path,site,calls in stops:out.append(f'| `{path}` | {site} | {calls} |')
        out.append('')
        assumptions=[l[len("assumption: "):] for l in survey_text.splitlines() if l.startswith('assumption: ')]
        out.append(f'Assumptions reported by the runtime: {len(assumptions)} (full text in the survey file).\n')
    out.append('## Source tree (layers, lowest first)\n')
    out.append('| Layer | Files | Lines |\n|---|---|---|')
    for a in sorted(layers,key=lambda a:(LAYERS.index(a) if a in LAYERS else 99,a)):out.append(f'| `src/{a}` | {layers[a][0]} | {layers[a][1]} |')
    out.append(f'| total | {sum(v[0] for v in layers.values())} | {sum(v[1] for v in layers.values())} |\n')
    readable = readability_snapshot(ROOT)
    out.append('## Readability (current source)\n')
    out.append(f'Game tier: {len(readable)} files; lexical counts from '
               '`tools/gate/check_readability.py`, ratcheted against '
               '`reference/readability-baseline.json`. Reference adapters are excluded.\n')
    for metric, count in readability_totals(readable).items():
        out.append(f'* {metric.replace("_", " ")}: {count}')
    out.append('')
    out.append('## Oracle map\n')
    out.append('One row per `tools/oracles/verify_original_<slug>.py` (`make oracle-<slug-with-dashes>` reruns it; `make oracles` all; tracked report `reference/oracle-reports/<slug>.json`).\n')
    out.append('| Oracle | Probe | Verdict |\n|---|---|---|')
    for slug,(v,why,probe) in oracles.items():out.append(f'| `{slug}` | {"yes" if probe else "no"} | {v} |')
    out.append('')
    out.append('## Hybrid runtime progress (M1+)\n')
    inv=ROOT/'reference/inventory/functions.json'
    if inv.exists():
        d=json.loads(inv.read_text());out.append(f'* Functions inventoried: {d["procedures"]}')
    else:out.append('* Function inventory is absent from this checkout (`docs/METHOD.md` section 2).')
    overrides=ROOT/'src/guest/override_table.cpp'
    if overrides.exists():
        out.append('* Reference override implementation: `src/guest/override_table.cpp` '
                   '(runtime binding is checked by the gate; source presence is not a runtime count).')
    else:out.append('* Reference override implementation is absent from this source tree.')
    coverage=next((p for p in (ROOT/'build/symbols/coverage.json', ROOT/'reference/symbols/coverage.json')
                   if p.exists()), None)
    if coverage is not None:
        c=json.loads(coverage.read_text())
        out.append(f'* Symbol names: {c["named_procedures"]} / {c["inventory_procedures"]} inventoried procedures '
                   f'({c["nonexternal_procedures"]} nonexternal).')
        out.append(f'* Named legacy owner addresses: {c["named_owner_addresses"]} / {c["legacy_owner_addresses"]}; '
                   f'unresolved addresses listed in `{coverage.relative_to(ROOT)}`.')
    out.append('')
    (ROOT/'docs/STATUS.md').write_text('\n'.join(out)+'\n')
    print('docs/STATUS.md written')
    return 0
if __name__=='__main__':sys.exit(main())
