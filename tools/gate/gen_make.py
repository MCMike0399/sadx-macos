#!/usr/bin/env python3
"""Generate build/tests.mk and build/oracles.mk.

Unit tests (tests/unit/manifest.tsv): `<test-name>\t<arguments>` -> one
`./build/<test-name>-test <arguments>` line in the run-unit-tests recipe.

Oracles are discovered, not listed: every tools/oracles/verify_original_<slug>.py becomes the
target `oracle-<slug-with-dashes>` with the default recipe

    $(REFERENCE_PYTHON) tools/oracles/verify_original_<slug>.py "$(GAME_EXE)" \
        build/native-<slug-with-dashes>-probe.dylib --output build/oracles/<slug>.json

depending on that probe. tools/oracles/manifest.tsv holds only the exceptions:
`<slug>\t<prerequisites>\t<command after $(REFERENCE_PYTHON)>` replaces the default recipe for
that slug (extra inputs such as a DLL, `assets`, an asset directory). A manifest row for a slug
with no script is an error, so the manifest cannot drift.
"""
import pathlib,sys
ROOT=pathlib.Path(__file__).resolve().parents[2]
def rows(path):
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith('#'):continue
        yield line.split('\t')
def oracle_recipes():
    scripts=sorted(p.name[len('verify_original_'):-3] for p in (ROOT/'tools/oracles').glob('verify_original_*.py'))
    overrides={r[0]:(r[1],r[2]) for r in rows(ROOT/'tools/oracles/manifest.tsv')}
    unknown=set(overrides)-set(scripts)
    if unknown:raise SystemExit(f'tools/oracles/manifest.tsv names oracles without a script: {sorted(unknown)}')
    recipes=[]
    for slug in scripts:
        dashed=slug.replace('_','-');probe=f'build/native-{dashed}-probe.dylib'
        if slug in overrides:pre,cmd=overrides[slug]
        else:pre,cmd=probe,f'tools/oracles/verify_original_{slug}.py "$(GAME_EXE)" {probe} --output build/oracles/{slug}.json'
        recipes.append((f'oracle-{dashed}',pre,cmd))
    return recipes
def main():
    out=ROOT/'build';out.mkdir(exist_ok=True);(out/'oracles').mkdir(exist_ok=True)
    tests=list(rows(ROOT/'tests/unit/manifest.tsv'))
    lines=['# generated by tools/gate/gen_make.py from tests/unit/manifest.tsv; do not edit','run-unit-tests:']
    for row in tests:
        name=row[0];args=row[1] if len(row)>1 else ''
        lines.append(f'\t/usr/bin/time -p ./build/{name}-test {args}'.rstrip())
    (out/'tests.mk').write_text('\n'.join(lines)+'\n')
    recipes=oracle_recipes()
    lines=['# generated by tools/gate/gen_make.py from tools/oracles/*.py + manifest.tsv; do not edit']
    lines.append('.PHONY: '+' '.join(t for t,_,_ in recipes))
    lines.append('ORACLE_TARGETS := '+' '.join(t for t,_,_ in recipes))
    for target,pre,cmd in recipes:
        lines.append(f'{target}: {pre} | build/oracles')
        lines.append(f'\t$(REFERENCE_PYTHON) {cmd}')
    lines.append('build/oracles:\n\tmkdir -p build/oracles')
    (out/'oracles.mk').write_text('\n'.join(lines)+'\n')
    print(f'{len(tests)} unit tests, {len(recipes)} oracle targets')
    return 0
if __name__=='__main__':sys.exit(main())
