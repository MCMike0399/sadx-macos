#!/usr/bin/env python3
"""Generate build/tests.mk and build/oracles.mk from the two manifests.

tests/unit/manifest.tsv:   <test-name>\t<arguments>   (one `./build/<test-name>-test args` line each)
tools/oracles/manifest.tsv: <target>\t<prerequisites>\t<command after $(REFERENCE_PYTHON)>

The Makefile includes the generated files and remakes them when a manifest
changes, so adding a test or an oracle is one line in one place.
"""
import pathlib,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
def rows(path):
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith('#'):continue
        yield line.split('\t')
def main():
    out=ROOT/'build';out.mkdir(exist_ok=True)
    tests=list(rows(ROOT/'tests/unit/manifest.tsv'))
    lines=['# generated by tools/gen_make.py from tests/unit/manifest.tsv; do not edit','run-unit-tests:']
    for row in tests:
        name=row[0];args=row[1] if len(row)>1 else ''
        lines.append(f'\t./build/{name}-test {args}'.rstrip())
    (out/'tests.mk').write_text('\n'.join(lines)+'\n')
    oracles=list(rows(ROOT/'tools/oracles/manifest.tsv'))
    lines=['# generated by tools/gen_make.py from tools/oracles/manifest.tsv; do not edit']
    lines.append('.PHONY: '+' '.join(r[0] for r in oracles))
    lines.append('ORACLE_TARGETS := '+' '.join(r[0] for r in oracles))
    for target,pre,cmd in oracles:
        lines.append(f'{target}: {pre}')
        lines.append(f'\t$(REFERENCE_PYTHON) {cmd}')
    (out/'oracles.mk').write_text('\n'.join(lines)+'\n')
    print(f'{len(tests)} unit tests, {len(oracles)} oracle targets')
    return 0
if __name__=='__main__':sys.exit(main())
